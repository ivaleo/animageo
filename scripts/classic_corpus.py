#!/usr/bin/env python3
"""Regression corpus of the classic renderer: .ggb drawings, DSL and animations.

    python scripts/classic_corpus.py record  [CORPUS] [-m manifest.json]
    python scripts/classic_corpus.py verify  [CORPUS] [-m manifest.json]
    python scripts/classic_corpus.py compare [CORPUS] --base OLD_CHECKOUT [--md report.md]

``CORPUS`` is a directory (searched recursively; default: the environment
variable ``ANIMAGEO_CORPUS``). The corpus files stay outside the repository:
only this runner and the numbers it prints are kept here. A scene is

- ``x.ggb`` — the drawing alone: ``loadGGB(x, generate_stubs=False)`` →
  ``exportSVG`` (the classic path of the web service);
- ``x.dsl`` next to ``x.ggb`` — a DSL block over the drawing, as the web
  runs it: ``loadGGB`` → ``putCode(block)`` → the new elements are drawn →
  ``exportSVG``;
- ``x.py`` — a DSL scene alone: ``loadCode(x.py)`` → ``exportSVG``;
- ``x.animation.json`` next to ``x.ggb`` — a timeline of the web
  (``{fps, resolution, timeline}``): the scene code is generated by the web
  service (``app/services/animation_export.py`` of the checkout given with
  ``--web`` or ``ANIMAGEO_WEB``), manim renders its last frame (PNG,
  ``-ql -s``) and, for the first ``--video N`` animations, a short low
  quality video (compared frame by frame). Without a web checkout the
  animations are skipped.

Files and directories whose name starts with ``_`` or ``.`` are skipped.
Every scene renders in a fresh subprocess of this interpreter with
``PYTHONPATH`` set to the library checkout (and the web checkout for
animations); the subprocess reports the time of ``import``, ``loadGGB``, the
code and the export.

``record`` writes ``{format, animageo, manim, python, files: {path:
"sha256:…"}}``; ``verify`` renders again and lists every scene whose hash
differs, that failed or that is missing on either side (exit 1).
``compare --base`` renders every scene with an older checkout of the library
and with this one, and sorts the pairs: ``same`` (byte for byte),
``same-normalized`` (an SVG equal after numbers are rounded and ids
renumbered, a PNG with equal pixels, a video with equal frames),
``different``, ``failed-both`` (an old failure kept), ``fixed`` (failed
before, renders now) and ``broken`` (rendered before, fails now); it exits 1
on ``different`` or ``broken``. ``--keep DIR`` keeps the outputs.

``--diffs FILE`` (``verify`` and ``compare``; default
``docs/native/classic-diffs.json``) lists the intended differences of the
classic renderer: ``{format, diffs: {scene id: {item, changelog}}}`` — the
scene, the item of the kernel spec §15 that changed it and its line of the
CHANGELOG. A listed scene that changed is ``expected``, not a failure; a
listed scene that did not change is reported, so the list stays true.

The plan for 1.8.0a1 asks for at least 30 ``.ggb`` and 20 DSL scenes; a
smaller corpus is reported, not refused. Needs manim (and cairo) on the
machine; this script itself only starts subprocesses and does not import
manim.
"""
